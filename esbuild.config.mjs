import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { existsSync, mkdirSync, copyFileSync, readFileSync } from "fs";
import { join } from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, visit the plugin's github repository
*/
`;

const prod = process.argv[2] === "production";

// Where to drop the built plugin so Obsidian picks it up. Kept out of git:
// set OBSIDIAN_VAULT, or write the vault path into a .vault-path file.
function vaultPluginDir() {
  let vault = process.env.OBSIDIAN_VAULT;
  if (!vault && existsSync(".vault-path")) {
    vault = readFileSync(".vault-path", "utf8").trim();
  }
  if (!vault) return null;
  const { id } = JSON.parse(readFileSync("manifest.json", "utf8"));
  const dir = join(vault, ".obsidian", "plugins", id);
  mkdirSync(dir, { recursive: true });
  return dir;
}

// Build straight into the vault whenever one is configured, in both modes:
// `npm run dev` then gives a watch loop, and `npm run build` installs the
// minified bundle. With OBSIDIAN_VAULT unset it writes ./main.js, which is
// what a release archive wants.
const outDir = vaultPluginDir();
const outfile = outDir ? join(outDir, "main.js") : "main.js";

// Obsidian reloads a plugin when it sees main.js change, so copying the
// manifest alongside the bundle is enough for the dev loop.
const syncManifest = {
  name: "sync-manifest",
  setup(build) {
    build.onEnd(() => {
      if (!outDir) return;
      copyFileSync("manifest.json", join(outDir, "manifest.json"));
      copyFileSync("styles.css", join(outDir, "styles.css"));
      console.log(`built -> ${outfile}`);
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile,
  minify: prod,
  plugins: [syncManifest],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
